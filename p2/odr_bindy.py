"""Python port of ODR-BINDy (Fung et al., arXiv:2507.23426).

Reference implementation: MATLAB package https://github.com/llfung/ODR-BINDy
(MIT licence, (c) 2025 Lloyd Fung). Files ported, with their Python names:

  DerivativeUtils/FD.m                  -> fd_matrices           (interior stencils only)
  lib_func/Polynomial{D}D{O}O[d|dd].m   -> PolynomialLibrary     (generic, same term order)
  ODR-DynSys/EnsembleLinRegress_Wprior  -> ensemble_lin_regress_wprior
  ODR-DynSys/Jsq_xp.m                   -> jsq_xp
  ODR-DynSys/d2Jdp2_GaussNewtonEst.m    -> d2jdp2_gauss_newton_est
  ODR-DynSys/ODR_BINDy_Regression.m     -> odr_bindy_regression
  FullGreedy/ODR_BINDy_Greedy.m         -> odr_bindy_greedy (incl. RemovalDecision)

Structure and defaults are those of the MATLAB code: MaxNoiseIter=2,
StepTolerance=1e-12, LinUseDenoise=True, MinInitialTrial=4,
MaxInitialTrial=16, MaxFailedRun=2, ContRunStop=2, IniGuessUsePrev=True,
UseGaussNewtonEst=True; lsqnonlin FunctionTolerance=5e-8, MaxIterations
100 (candidate fits) / 1000 doubling on each initial trial; ensemble
initial guess 100 / 1000 bootstrap samples with bragging (median); the
Lorenz.m hyper-parameters SigmaY=1e-4, SigmaP=1e2, 6th-order FD.

Differences from MATLAB (and why)
---------------------------------
1. Optimiser: MATLAB ``lsqnonlin`` ('trust-region-reflective', no bounds,
   default PrecondBandWidth=Inf i.e. direct factorisation of the GN system)
   is replaced by ``_lsqnonlin``: Gauss-Newton steps from an exact structured
   solve of J'J s = -J'r (banded Cholesky of the x-block after point-major
   reordering + Schur complement for p, Jacobi-scaled), globalised by
   Armijo step-halving. Why: the problem is extremely stiff (residuals scaled
   by 1/SigmaY = 1e4 vs 1/SigmaX ~ 0.4; cond(J'J) ~ 1e16). Tried and rejected
   on the Lorenz full-library fit: scipy least_squares(trf, lsmr) did not
   converge in 1000 evaluations (92 s); a hand-written unscaled/scaled 2-D
   subspace trust region (MATLAB's TRF step) and MATLAB-rule Levenberg-
   Marquardt both stalled at resnorm 1.7e3-2.6e6 after 300-1000 iterations,
   while the GN line search reaches resnorm 1445.5 in 25 iterations (4 s).
   Stop tests: |df| <= FunctionTolerance(5e-8)*(1+f), |step| <=
   StepTolerance*(1+|x|), |grad|_inf < 1e-6; MaxIterations 100 / 1000 as in
   MATLAB. Exit flags: >0 converged, 0 = MaxIterations, -99 = exception.
2. Only the default Hessian path (UseGaussNewtonEst=True, d2Jdp2_GaussNewtonEst)
   is ported. The full d2Jdp2.m / dJdx.m / Jsq_x.m path is used only when
   UseGaussNewtonEst=False, which neither the greedy default nor Lorenz.m uses.
   Requesting it raises NotImplementedError instead of silently substituting.
3. Random numbers: MATLAB ``bootstrp``/``randn`` streams cannot be reproduced;
   numpy ``Generator`` streams are used (seedable via ``seed``). Hence the
   noisy Lorenz data are statistically, not bitwise, identical to rng(12).
4. FD.m: only the interior (FullMatFlag=false) branch, as used by Lorenz.m.
   Stencils are generated by the same Vandermonde solve as CentralFD (exactly
   equal to the hard-coded 2/4/6/8/10 rows).
5. Library: one generic polynomial generator replaces the per-dimension
   hand-written files; term order (1, x, y, z, x^2, xy, xz, y^2, yz, z^2, ...)
   matches Polynomial3D2O / Polynomial3D3O. Third derivatives are not needed
   on the Gauss-Newton path and are not provided.
6. Plotting, SaveProgress/LoadProgressFile are dropped (I/O only).
7. The ``chol`` fallback ``logdet`` (MATLAB File-Exchange helper) is replaced
   by ``numpy.linalg.slogdet``.

Layout convention (identical to MATLAB): parameter mask is a flat
column-major (Fortran) boolean vector of length M*ND; x vectors are the
Fortran-flattened (Nx, ND) state; p is ordered equation-by-equation.
"""
