def fit(F_cols: dict, dt: float, sigma_x, poly_order: int = 2, fd_order: int = 6,
        sigma_y: float = 1e-4, sigma_p: float = 1e2, options=None, seed: int = 0):
    """Fit ODR-BINDy to equally spaced state columns.

    F_cols: {state name: 1-D array (Nx,)}; sigma_x: scalar or dict of noise STDs.
    Returns dict(Xi {state: {term: coef}}, coef (M,ND), terms, states,
    X_denoised {state: array}, J_evidence, runtime_s).
    """
    names = list(F_cols)
    X = np.column_stack([np.asarray(F_cols[k], float) for k in names])
    Nx, ND = X.shape
    lib = PolynomialLibrary(ND, poly_order, names)
    IMat, DMat = fd_matrices(Nx, fd_order, dt)
    sx = np.array([sigma_x[k] for k in names]) if isinstance(sigma_x, dict) \
        else np.full(ND, float(sigma_x))
    t0 = time.perf_counter()
    Xi, J, Xd, hist = odr_bindy_greedy(
        X, lib, IMat, DMat, np.tile(sx, (Nx, 1)), sigma_y * np.ones((IMat.shape[0], ND)),
        sigma_p * np.ones((lib.M, ND)), options, seed)
    return dict(
        Xi={s: {t: float(Xi[m, d]) for m, t in enumerate(lib.names) if Xi[m, d] != 0}
            for d, s in enumerate(names)},
        coef=Xi, terms=lib.names, states=names,
        X_denoised={s: Xd[:, d] for d, s in enumerate(names)},
        J_evidence=float(J), history=hist, runtime_s=time.perf_counter() - t0)
